#!/usr/bin/env node
/**
 * Ahead-of-time compilation of the JSON Schemas the frontend validates against.
 *
 * Ajv normally builds its validators with `new Function` the moment a module
 * calls `ajv.compile()`. In the VS Code webview that is fatal, not merely
 * untidy: the webview CSP has no `'unsafe-eval'`, so the very first import of
 * `file/schema.ts` or `library/catalog-core.ts` threw and the page rendered
 * nothing at all. `ajv/dist/standalone` solves this by emitting the validator
 * as ordinary ES module *source* here, at build time, so the browser only ever
 * imports plain JavaScript.
 *
 * Follows the convention of `packages/schemas/scripts/codegen.mjs`: output is
 * committed to the repo, and `--check` fails when it has drifted from the
 * schema sources (wired into `pnpm build` / `pnpm test` so it cannot go stale).
 *
 * Run: pnpm -F @gensim/frontend gen:validators
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const FRONTEND_ROOT = resolve(__dirname, "..");
const REPO_ROOT = resolve(FRONTEND_ROOT, "..", "..");
const DEFINITIONS = join(REPO_ROOT, "packages", "schemas", "definitions");
const OUT_DIR = join(FRONTEND_ROOT, "src", "generated", "validators");

const CHECK_MODE = process.argv.includes("--check");

function readSchema(...segments) {
  const path = join(DEFINITIONS, ...segments);
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    console.error(`gen-validators: cannot read schema ${relative(REPO_ROOT, path)}: ${error}`);
    process.exit(1);
  }
}

const PORT_KIND_ID = "https://general-simulator.dev/schemas/model/port-kind.schema.json";

/**
 * One entry per `ajv.compile()` call that used to happen at module scope.
 *
 * `ajvOptions` must stay identical to the options the runtime call site used,
 * otherwise the generated validator would silently accept or reject different
 * documents than the code it replaces.
 */
const TARGETS = [
  {
    label: "gsim_sch",
    // Mirrors apps/frontend/src/file/schema.ts.
    ajvOptions: { allErrors: true, strict: true },
    referenced: [],
    schema: () => readSchema("model", "gsim_sch.schema.json"),
    basename: "gsim-sch",
    exportName: "validateGsimSchDocument",
    typeImport: 'import type { ModelDocument } from "../../model/types";',
    validatedType: "ModelDocument",
  },
  {
    label: "block_metadata",
    // Mirrors apps/frontend/src/library/catalog-core.ts.
    ajvOptions: { strict: true, allErrors: true },
    referenced: [{ id: PORT_KIND_ID, schema: () => readSchema("model", "port-kind.schema.json") }],
    schema: () => readSchema("blocks", "block-metadata.schema.json"),
    basename: "block-metadata",
    exportName: "validateBlockMetadataSchema",
    typeImport: 'import type { BlockMetadata } from "../../model/types";',
    validatedType: "BlockMetadata",
  },
];

const BANNER = `\
// AUTO-GENERATED by apps/frontend/scripts/gen-validators.mjs
// Do not edit manually - run: pnpm -F @gensim/frontend gen:validators
// Source: packages/schemas/definitions/
//
// Precompiled ahead of time so no JSON Schema validator is built by runtime
// code generation, which the VS Code webview CSP forbids.
// See apps/vscode-extension/src/webview-html.ts.
`;

/**
 * Turn the last CommonJS `require()` calls in Ajv's "ESM" output into imports.
 *
 * `code: {esm: true}` only switches the module's *exports*; the small runtime
 * helpers Ajv pulls into a validator's scope (currently just `ucs2length`) are
 * still emitted as `require("ajv/dist/runtime/…").default`. That is a genuine
 * Ajv gap, and it is fatal here twice over: `require` is not defined in an ES
 * module, and a bundler cannot see through it either.
 *
 * Every helper Ajv reaches for this way is a plain function, but *how deeply
 * it is wrapped* depends on the loader: Node's CJS-ESM interop exposes
 * `module.exports` as the namespace's `default`, so the function ends up at
 * `ns.default.default`, while Vite honours the `__esModule` marker and puts it
 * at `ns.default`. Unwrapping `.default` until a function falls out is correct
 * under both, and `assertRuntimeHelpersAreFunctions` below checks the premise.
 */
const INTEROP_HELPER = "__ajvInterop";
const INTEROP_HELPER_SOURCE = `\
// Unwrap CommonJS/ESM interop until the helper function itself falls out; how
// many \`.default\` hops that takes differs between Node and a bundler.
const ${INTEROP_HELPER} = (m) =>
  typeof m === "function" ? m : m && typeof m === "object" && "default" in m ? ${INTEROP_HELPER}(m.default) : m;`;

/** Every Ajv runtime helper the generated validators pull in, for the check below. */
const runtimeHelperModules = [];

/**
 * The `__ajvInterop` unwrap assumes each helper is ultimately a function.
 * If a future Ajv version scopes in a non-function (a regexp table, say),
 * unwrapping would hand the validator the wrong value and it would fail far
 * from here, so make that a codegen-time error instead.
 */
async function assertRuntimeHelpersAreFunctions() {
  for (const specifier of [...new Set(runtimeHelperModules)]) {
    const namespace = await import(specifier);
    let value = namespace;
    while (value && typeof value === "object" && "default" in value) {
      value = value.default;
    }
    if (typeof value !== "function") {
      console.error(
        `gen-validators: runtime helper '${specifier}' resolves to ${typeof value}, not a function. The generated interop unwrap assumes a function - update esmify().`,
      );
      process.exit(1);
    }
  }
}

function esmify(code, label, modulesImported) {
  const imports = [];
  const identifiers = new Map();

  const rewritten = code.replace(
    /require\((["'])([^"']+)\1\)(\.default)?/g,
    (_match, _quote, moduleId, defaultAccess) => {
      const key = `${moduleId}${defaultAccess ?? ""}`;
      let identifier = identifiers.get(key);
      if (!identifier) {
        identifier = `__ajvRuntime${identifiers.size}`;
        identifiers.set(key, identifier);
        const namespace = `${identifier}Ns`;
        // Ajv writes these as extensionless deep paths, which CommonJS resolves
        // but strict ES module resolution (plain Node, and Vite in dev) does
        // not. Ajv publishes no `exports` map covering them, so spell out the
        // file extension it omits.
        const specifier = /\/[^/.]+$/.test(moduleId) ? `${moduleId}.js` : moduleId;
        imports.push(
          `import * as ${namespace} from ${JSON.stringify(specifier)};`,
          `const ${identifier} = ${INTEROP_HELPER}(${namespace});`,
        );
        modulesImported.push(specifier);
      }
      return identifier;
    },
  );

  if (/\brequire\s*\(/.test(rewritten)) {
    console.error(`gen-validators: '${label}' still contains a require() call after rewriting.`);
    process.exit(1);
  }

  if (imports.length === 0) {
    return rewritten;
  }

  const preamble = [INTEROP_HELPER_SOURCE, ...imports].join("\n");

  // Ajv opens its output with `"use strict";`, which must stay the first
  // statement; imports are hoisted anyway, so put them straight after it.
  const prologue = '"use strict";';
  if (!rewritten.startsWith(prologue)) {
    return `${preamble}\n${rewritten}`;
  }
  return `${prologue}\n${preamble}\n${rewritten.slice(prologue.length)}`;
}

function generate(target) {
  const ajv = new Ajv2020({ ...target.ajvOptions, code: { source: true, esm: true } });
  for (const ref of target.referenced) {
    ajv.addSchema(ref.schema(), ref.id);
  }
  const validate = ajv.compile(target.schema());
  const runtimeModules = [];
  const code = esmify(standaloneCode(ajv, validate), target.label, runtimeModules);
  runtimeHelperModules.push(...runtimeModules);

  // Belt and braces: the whole point of this script is that nothing downstream
  // evaluates a string as code, so refuse to emit output that would. Checked
  // against Ajv's output alone - the banner below talks *about* `new Function`.
  if (/\bnew Function\b|\beval\s*\(/.test(code)) {
    console.error(
      `gen-validators: refusing to emit '${target.label}' - Ajv's standalone output contains a runtime code-generation construct, which defeats the purpose of precompiling.`,
    );
    process.exit(1);
  }

  // Ajv names the default export `validate`; re-export it under a descriptive
  // name so the two generated modules do not read identically at call sites.
  const js = `${BANNER}${code}\nexport { validate as ${target.exportName} };\n`;

  const dts = `${BANNER}
${target.typeImport}

export interface GeneratedValidationError {
  instancePath: string;
  schemaPath: string;
  keyword: string;
  message?: string;
  params: Record<string, unknown>;
}

/**
 * Precompiled Ajv validator. Narrows on success; on failure the offending
 * errors are attached to \`.errors\`, exactly as a runtime-compiled Ajv
 * validator behaves.
 */
export interface GeneratedValidator<T> {
  (data: unknown): data is T;
  errors?: GeneratedValidationError[] | null;
}

export declare const ${target.exportName}: GeneratedValidator<${target.validatedType}>;
export declare const validate: GeneratedValidator<${target.validatedType}>;
export default validate;
`;

  return [
    { path: join(OUT_DIR, `${target.basename}.js`), content: js },
    { path: join(OUT_DIR, `${target.basename}.d.ts`), content: dts },
  ];
}

const outputs = TARGETS.flatMap((target) => {
  try {
    return generate(target);
  } catch (error) {
    console.error(`gen-validators: failed to compile '${target.label}': ${error}`);
    process.exit(1);
  }
});

await assertRuntimeHelpersAreFunctions();

if (!CHECK_MODE) {
  mkdirSync(OUT_DIR, { recursive: true });
  for (const { path, content } of outputs) {
    writeFileSync(path, content, "utf8");
    console.log(`gen-validators: wrote ${relative(REPO_ROOT, path)}`);
  }
  console.log("gen-validators: done. Commit the generated files if they changed.");
  process.exit(0);
}

let drift = false;
for (const { path, content } of outputs) {
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {
    drift = true;
    console.error(`gen-validators: target missing: ${relative(REPO_ROOT, path)}`);
    continue;
  }
  if (current !== content) {
    drift = true;
    console.error(`gen-validators: target is out of date: ${relative(REPO_ROOT, path)}`);
  }
}

if (drift) {
  console.error("gen-validators: drift detected. Run pnpm -F @gensim/frontend gen:validators.");
  process.exit(1);
}

console.log("gen-validators: no drift detected.");
