"""BE-41 — v2 fixture roundtrip test.

Verifies that load() followed by write() of the comprehensive v2 fixture
produces byte-exact output — i.e. the fixture is already in canonical form
and write(load(fixture)) == fixture_text.

This ensures the fixture can be used as a single source of truth between
the backend (BE-41) and the frontend (FE-63) without silent reformatting.

No host SPICE simulator is required.
"""

from __future__ import annotations

import pathlib

import pytest

from simulator.compiler.gsim_sch_loader import load
from simulator.compiler.gsim_sch_writer import write

# ---------------------------------------------------------------------------
# Fixture path (single source of truth shared with FE-63)
# ---------------------------------------------------------------------------

REPO_ROOT = pathlib.Path(__file__).parents[3]
FIXTURE_PATH = REPO_ROOT / "tests" / "fixtures" / "gsim_sch" / "comprehensive.gsim_sch"


# ---------------------------------------------------------------------------
# Tests
# ---------------------------------------------------------------------------


def test_v2_roundtrip_byte_exact() -> None:
    """write(load(fixture)) == fixture bytes — canonical-form roundtrip.

    The fixture was generated by gsim_sch_writer.write() (see the fixture
    generation note at the top of BE-41).  Loading it and writing it back
    must produce byte-identical output, confirming:

    1. The fixture satisfies JSON Schema validation on every load.
    2. Key ordering, indentation, and line endings are already canonical.
    3. No normalisation is silently applied on ingest.

    If this test fails it means the fixture was edited by hand in a way that
    diverges from the canonical form.  Re-generate it with the writer.
    """
    if not FIXTURE_PATH.exists():
        pytest.skip(f"Fixture not found: {FIXTURE_PATH}")

    original_text = FIXTURE_PATH.read_text(encoding="utf-8")
    doc = load(FIXTURE_PATH)
    written_text = write(doc)

    assert written_text == original_text, (
        "write(load(fixture)) is NOT byte-exact.\n"
        "The fixture has likely been edited by hand out of canonical form.\n"
        "Re-generate it with the gsim_sch_writer: "
        "write() output must match the fixture file exactly."
    )


def test_v2_roundtrip_fixture_exists() -> None:
    """The comprehensive fixture file exists at the expected path."""
    assert FIXTURE_PATH.exists(), (
        f"Fixture not found at {FIXTURE_PATH}.\n"
        "This file is the single source of truth shared between BE-41 and FE-63."
    )


def test_v2_roundtrip_loads_valid() -> None:
    """The fixture loads without validation errors (schema_version=2, params resolved)."""
    if not FIXTURE_PATH.exists():
        pytest.skip(f"Fixture not found: {FIXTURE_PATH}")

    doc = load(FIXTURE_PATH)

    assert doc.schema_version == 2
    # Params A and B should be resolved
    assert doc.resolved_params.get("A") == pytest.approx(5.0), (
        f"Expected A=5.0, got {doc.resolved_params.get('A')}"
    )
    assert doc.resolved_params.get("B") == pytest.approx(10.0), (
        f"Expected B=10.0 (={'{A * 2}'}), got {doc.resolved_params.get('B')}"
    )
