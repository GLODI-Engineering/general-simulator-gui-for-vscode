#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SCHEMAS_ROOT = resolve(__dirname, "..");
const CHECK_MODE = process.argv.includes("--check");

const SCHEMA_FILES = {
  gsimSch: join(SCHEMAS_ROOT, "definitions", "model", "gsim_sch.schema.json"),
  portKind: join(SCHEMAS_ROOT, "definitions", "model", "port-kind.schema.json"),
  blockMeta: join(SCHEMAS_ROOT, "definitions", "blocks", "block-metadata.schema.json"),
};

for (const [key, path] of Object.entries(SCHEMA_FILES)) {
  try {
    JSON.parse(readFileSync(path, "utf8"));
  } catch {
    console.error(`codegen: cannot read schema source '${key}' at ${path}`);
    process.exit(1);
  }
}

