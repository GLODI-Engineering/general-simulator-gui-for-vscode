if (!CHECK_MODE) {
  for (const { relPath, content, label } of TARGETS) {
    const outPath = join(SCHEMAS_ROOT, relPath);
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, content, "utf8");
    console.log(`codegen: wrote ${label} -> ${relPath}`);
  }
  console.log("codegen: done. Commit the generated files if they changed.");
  process.exit(0);
}

let drift = false;
for (const { relPath, content, label } of TARGETS) {
  const outPath = join(SCHEMAS_ROOT, relPath);
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    drift = true;
    console.error(`codegen: ${label} target missing: ${relPath}`);
    continue;
  }
  if (current !== content) {
    drift = true;
    console.error(`codegen: ${label} target is out of date: ${relPath}`);
  }
}

if (drift) {
  console.error("codegen: drift detected. Run pnpm -F @gensim/schemas codegen.");
  process.exit(1);
}

console.log("codegen: no drift detected.");
